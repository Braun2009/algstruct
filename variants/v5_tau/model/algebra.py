"""Algebraic structure stream in a language-model-shaped backbone.

Follows `docs/DESIGN.md`; when code and that page disagree, the page wins.

Two streams. The semantic side aggregates (attention: commutative, averageable).
The structural side composes (matrix multiplication: non-commutative, partially
invertible). They meet only at an interface.

Per structural layer, per token:

    d_t   = W_d h_t                                  semantic -> structure (a source)
    da    = -grad V(a) - D(a) sym(a) - Omega(a) skew(a) + d_t
    a    <- a + dt * da / (1 + |da|/limit)           encoding, then traceless
    A     = Cayley(skew a) @ P(a)                    ||A||_2 <= 1 by construction
    Z     = A @ Z,   Z_0 = I                         computation: composition
    s     = W_s h                                    interface: semantic -> structure
    h    <- h + W_o vec(rho(Z, s))                   action -> interface back

`rho(Z, s) = Z s` with `s` viewed as k x q. It is a representation:
rho(Z2 Z1) = rho(Z2) rho(Z1) exactly. That is the only way to make an algebra
element act on a vector space while keeping both the composition law and the
non-commutativity. It has no parameters -- the form of the action is not
learned, what is learned is the interface around it.

Why the interface: `s = h.reshape(k, w/k)` would assert that residual-stream
dimensions 0..w/k-1 are structural slot 0. That has no reason to hold: the
residual basis grows out of the semantic side, which optimises aggregation, not
composition. With W_s and W_o the composite map is W_o (Z kron I) W_s h, which
at W_o = W_s^-1 is the conjugate representation of Z: same conjugacy class, so
Z keeps its algebraic identity (trace, spectrum, non-normality) while acting.

The interface is free; the operator is not. Z is k^2 numbers, generated by 7
global coefficients along the sequence, shared across all q blocks. That is the
line between this and a free linear map.

Arms
    full       as above
    nocompose  Z = A_t: per-token transform kept, accumulation removed
    nodrive    d_t = 0: the semantic stream cannot reach the law
    off        no structural stream (plain transformer baseline)
"""
from __future__ import annotations

from dataclasses import dataclass
import math
import os

import torch
from torch import Tensor, nn
from torch.nn import functional as F

from .action import rho_split
from .block import LocalBlock

ARMS = ('full', 'nocompose', 'nodrive', 'off')


def _advance(a: Tensor, drive: Tensor, tau: Tensor, v: Tensor, d0: Tensor,
             d1: Tensor, w0: Tensor, w1: Tensor, step_limit: float,
             a_limit: float, eye: Tensor) -> Tensor:
    """One encoding step in structural proper time `tau` (b, 1, 1).

    The ODE is written in proper time d(tau) instead of token index:
        da / dtau = -grad V(a) - D(a) sym(a) - Omega(a) skew(a) + drive
        dZ / dtau = skew(a) Z
    When tau_t -> 0 (e.g. a no-op / NOISE token), both a_t = a_{t-1} and
    R_t = exp(tau_t skew(a_t)) = I, so the structural stream is invariant to
    inserting arbitrary filler tokens between real operations.
    """
    r2 = a.square().sum((-1, -2), keepdim=True)
    c = a @ a.mT - a.mT @ a
    grad = 2 * v[0] * a.mT + 2 * v[1] * a + 4 * v[2] * (c @ a - a @ c)
    dissip = d0 + d1 * r2
    gyro = w0 + w1 * r2
    da = -grad - dissip * (.5 * (a + a.mT)) - gyro * (.5 * (a - a.mT)) + drive
    da = da / (1. + da.norm(dim=(-2, -1), keepdim=True) / step_limit)
    a = a + tau * da
    tr = a.diagonal(dim1=-2, dim2=-1).sum(-1) / a.shape[-1]
    a = a - tr[..., None, None] * eye
    # smooth rescale onto the ball: exact below the limit, norm-preserving above
    n = a.norm(dim=(-2, -1), keepdim=True)
    return a * (a_limit / n.clamp(min=a_limit))


if os.environ.get('ALG_EAGER'):
    _advance_c = _advance
else:
    _advance_c = torch.compile(_advance, dynamic=True)


@dataclass
class AlgebraConfig:
    width: int = 192
    layers: int = 6
    k: int = 3
    q: int = 64                 # bandwidth per slot; structural space is k*q wide
    drive_scale: float = .1    # target |d_t|; see Generator for why this number
    window: int | None = None
    state_layers: tuple = (1, 3)
    arm: str = 'full'
    dt: float = 1.0             # maximum proper-time step per token
    tau_bias: float = -2.0      # initial logit for tau; sigmoid(-2) ~ 0.12
    memory: float = 2.0         # proper-time units; sets v3 = 1/(2 memory dt)
    out_init: float = 3e-3      # std of the readout interface; 0 restores the mainline
    step_limit: float = 6.0     # trust region on |da| per proper-time unit
    a_limit: float = 5.0        # bound on |a| itself; covers sqrt(2)*pi = 4.44
    skew_limit: float = 1.2     # unused by exp map; kept for config parity


def _inv_softplus(y: float) -> float:
    """raw value whose softplus is y, so initialisation can be stated in the
    physical units (amplitudes, memory) rather than in raw parameters."""
    return math.log(math.expm1(y))


def cayley(a: Tensor) -> Tensor:
    """R = (I - a/2)^{-1} (I + a/2) for skew a: exactly orthogonal."""
    k = a.shape[-1]
    eye = torch.eye(k, dtype=a.dtype, device=a.device)
    half = .5 * a
    return torch.linalg.solve(eye - half, eye + half)


class Generator(nn.Module):
    """The 7 coefficients of the law, shared by every structural layer.

    One set for the whole model. That is the strongest version of "one
    generator, many modes": the law converges, the adaptation diverges. With a
    separate set per layer there would be several generators, and "one law grew
    this dynamics" would not be measurable.

    v2, v3, v4 are softplus-positive so that V is coercive -- a cubic invariant
    such as det a is unbounded below, so the relaxation would have no minimum.
    Tr a is absent: a is projected to traceless every step, so that term would
    be a constant with zero gradient.

    v3 = v2 + softplus(.) is not a detail. For purely antisymmetric a,
    V(skew) = (v3 - v2) |a|^2, and at v3 = v2 the potential is exactly flat on
    that whole subspace. Since D only acts on the symmetric part and Omega
    starts at zero, the antisymmetric half would then be an undamped
    integrator: da_skew = d_t,skew, accumulating until skew_limit clamps it,
    after which the Cayley map saturates and the gradient dies. Coercivity on
    both halves is what makes "relax toward a minimum" meaningful.

    The initial values are chosen in physical units, because the law sets the
    *time constant* and nothing else:

        memory (tokens)      = 1 / (dt * 2 v3)
        equilibrium |a|      ~ |d| / (2 v3)

    With the original v3 = softplus(.5) = .974 the restoring rate was 2 v3 = 3.9,
    i.e. 0.39 per step at dt = .1: the state forgot in 2.5 tokens, so a_t was a
    pointwise function of the current token, every A_t was effectively the same
    matrix, and Z_t = A^t was a position counter. Measured on that setting:
    ||[A_1, A_64]||_F = 0.0086, and the spread of |Z| across samples collapsed
    from 1.70 (drive) to 0.054 -- the composition threw away 30x of the content.

    The defaults below give memory = 1/(.1 * .25) = 40 tokens at T = 128: long
    enough that the product carries content, short enough to still respond.
    """

    def __init__(self, dt: float = .1, memory: float = 40.0):
        super().__init__()
        # The potential alone provides the restoring force; the dissipative
        # coefficient starts at zero, so the state is a leaky integrator whose
        # leak is exactly the potential. Adding d0 on top would shorten the
        # memory by an amount that is easy to lose track of.
        rate = 1.0 / (memory * dt)               # = 2 * v3
        v3 = .5 * rate
        v2 = .5 * v3                             # keeps v3 > v2 with margin
        v4 = .25 * v3
        self.raw_v = nn.Parameter(torch.tensor([_inv_softplus(v2),
                                                _inv_softplus(v3 - v2),
                                                _inv_softplus(v4)]))
        self.d = nn.Parameter(torch.tensor([0., 0.]))           # d0, d1
        self.omega = nn.Parameter(torch.tensor([0., 0.]))       # w0, w1

    def coeffs(self):
        v2 = F.softplus(self.raw_v[0])
        v = torch.stack((v2, v2 + F.softplus(self.raw_v[1]), F.softplus(self.raw_v[2])))
        return v, self.d[0], self.d[1], self.omega[0], self.omega[1]

    def values(self):
        """Plain floats, for reporting what the law actually became."""
        v, d0, d1, w0, w1 = self.coeffs()
        d = v.detach()
        return {'v2': float(d[0]), 'v3': float(d[1]), 'v4': float(d[2]),
                'd0': float(d0.detach()), 'd1': float(d1.detach()),
                'w0': float(w0.detach()), 'w1': float(w1.detach())}


class AlgebraState(nn.Module):
    """Encoding, computation and action of the structural stream for one layer."""

    def __init__(self, cfg: AlgebraConfig, gen: Generator):
        super().__init__()
        self.cfg = cfg
        self.k = cfg.k
        self.q = cfg.q
        self.gen = gen

        # semantic -> structure. The drive must not scale with |h|: the residual
        # stream grows with depth (measured 2578 by layer 4 in a w=768 model),
        # while the law's stiffness is a fixed number of parameters. Left
        # uncorrected the drive was ~0.46 and the restoring rate 3.9, so the
        # state forgot in 2.5 tokens and the product degenerated into a counter.
        # A norm in front of the projector pins |d| to the same scale at every
        # depth, and the weight std is then set by the amplitude we want.
        self.dn = nn.LayerNorm(cfg.width)
        self.to_drive = nn.Linear(cfg.width, cfg.k * cfg.k)
        nn.init.normal_(self.to_drive.weight,
                        std=cfg.drive_scale / (cfg.k * math.sqrt(cfg.width)))
        nn.init.zeros_(self.to_drive.bias)

        # proper-time step: one positive scalar per token in (0, dt).
        # Not a mode router -- a time reparametrization dtau/dt so that no-op
        # tokens need not advance the structural clock.
        self.to_tau = nn.Linear(cfg.width, 1)
        nn.init.normal_(self.to_tau.weight, std=1e-2)
        nn.init.constant_(self.to_tau.bias, cfg.tau_bias)

        # the interface. Per layer: what counts as a structural component
        # depends on depth.
        #
        # `out` is small-random rather than zero. Zero-init makes training start
        # exactly at `off`, which is what the mainline does and what makes the
        # two arms differ only by the structure. But it also means the structural
        # path contributes nothing at step 0, so its gradient is the gradient of
        # noise and the path has to bootstrap itself out of a flat solution. With
        # attention restricted to window 1 that bootstrap failed: measured loss
        # 1.790 = ln 6 (the uniform prediction over six orientations) for every
        # arm at 4000 steps, after a transient in which the structural path did
        # carry the answer (flip 0.775 at 1500 steps) and was then abandoned.
        #
        # A small random init gives the path something to be wrong about, so the
        # gradient is informative from step 1. The scale is deliberately tiny:
        # the contribution is |out| * |rho(Z,s)| ~ 3e-3 * 768, small next to a
        # residual stream of order 1e3 at this depth.
        self.to_s = nn.Linear(cfg.width, cfg.k * cfg.q, bias=False)
        self.out = nn.Linear(cfg.k * cfg.q, cfg.width, bias=False)
        nn.init.normal_(self.out.weight, std=cfg.out_init)
        if cfg.out_init == 0:
            nn.init.zeros_(self.out.weight)

    def coeffs(self):
        return self.gen.coeffs()

    def potential(self, a: Tensor, v: Tensor) -> Tensor:
        a2 = a @ a
        c = a @ a.mT - a.mT @ a
        return (v[0] * a2.diagonal(dim1=-2, dim2=-1).sum(-1)
                + v[1] * a.square().sum((-1, -2))
                + v[2] * c.square().sum((-1, -2)))

    def grad_potential(self, a: Tensor, v: Tensor) -> Tensor:
        """Analytic; agrees with autograd to 3.6e-15."""
        c = a @ a.mT - a.mT @ a
        comm = c @ a - a @ c
        return 2 * v[0] * a.mT + 2 * v[1] * a + 4 * v[2] * comm

    def flow(self, a: Tensor, drive: Tensor) -> Tensor:
        v, d0, d1, w0, w1 = self.coeffs()
        r2 = a.square().sum((-1, -2), keepdim=True)
        dissip = d0 + d1 * r2
        gyro = w0 + w1 * r2
        sym = .5 * (a + a.mT)
        skew = .5 * (a - a.mT)
        return -self.grad_potential(a, v) - dissip * sym - gyro * skew + drive

    def decompose(self, a: Tensor, tau: Tensor | None = None):
        """A = R P with ||R||_2 = 1 and ||P||_2 <= 1, exactly.

        v5_tau integrates dZ/dtau = skew(a) Z in structural proper time:
            R_t = exp(tau_t * skew(a_t))
        When tau_t -> 0, R_t = I exactly (no rotation on filler tokens).
        When tau_t ~ 1, R_t can reach full 180 deg rotations in a single token.
        """
        skew = .5 * (a - a.mT)
        sym = .5 * (a + a.mT)
        r = torch.matrix_exp(skew if tau is None else tau * skew)
        eye = torch.eye(self.k, dtype=a.dtype, device=a.device)
        with torch.no_grad():
            s64 = sym.detach().double()
            try:
                shift = torch.linalg.eigvalsh(s64)[..., -1:].unsqueeze(-1)
            except Exception:
                shift = s64.square().sum((-1, -2), keepdim=True).sqrt()
        p = torch.matrix_exp(sym - shift.to(sym.dtype) * eye)
        return r, p

    # ── the stream ─────────────────────────────────────────────────
    def _prefix_product(self, mats: Tensor) -> Tensor:
        """Inclusive prefix product of (b,t,k,k) matrices, in log2(t) matmuls.

        Z_t = A_t Z_{t-1} with Z_0 = I, so Z_t equals the prefix product
        A_t ... A_1. Matrices do not commute, which is why a plain cumprod is
        wrong and a doubling scan is used instead: after step d the entry at t
        holds the product over the last 2^d factors.
        """
        b, t, k, _ = mats.shape
        eye = torch.eye(k, dtype=mats.dtype, device=mats.device)
        out, step = mats, 1
        while step < t:
            shifted = eye.expand(b, t, k, k).clone()
            shifted[:, step:] = out[:, :-step]
            out = out @ shifted
            step *= 2
        return out

    def forward(self, h: Tensor, stats: dict | None = None):
        # the Cayley solve and matrix_exp are done in fp32 regardless of the
        # surrounding autocast: bf16 there costs accuracy and buys nothing
        dtype = h.dtype
        with torch.autocast(device_type=h.device.type, enabled=False):
            h32 = h.float()
            out = self._stream(h32, stats)
        return out.to(dtype)

    def _stream(self, h: Tensor, stats: dict | None = None):
        b, t, _ = h.shape
        k, q = self.k, self.q
        eye = torch.eye(k, dtype=h.dtype, device=h.device).expand(b, -1, -1).contiguous()
        a = torch.zeros(b, k, k, dtype=h.dtype, device=h.device)
        a_traj = []
        # Only the cheap elementwise part is sequential. matrix_exp and the
        # Cayley solve are done once, batched over all positions, because a_t
        # itself does not depend on Z.
        # W_d has no recurrence: apply it to the whole sequence in one GEMM
        # instead of one small GEMM per position
        if self.cfg.arm == 'nodrive':
            drives = torch.zeros(b, t, k, k, dtype=h.dtype, device=h.device)
            taus = torch.zeros(b, t, 1, 1, dtype=h.dtype, device=h.device)
        else:
            hn = self.dn(h)
            drives = self.to_drive(hn).reshape(b, t, k, k)
            taus = (self.cfg.dt * torch.sigmoid(self.to_tau(hn))).unsqueeze(-1)
        v, d0, d1, w0, w1 = self.coeffs()
        eye_a = torch.eye(k, dtype=h.dtype, device=h.device)
        for i in range(t):
            a = _advance_c(a, drives[:, i], taus[:, i], v, d0, d1, w0, w1,
                           self.cfg.step_limit, self.cfg.a_limit, eye_a)
            a_traj.append(a)
        a_seq = torch.stack(a_traj, 1)                       # (b,t,k,k)
        r, p = self.decompose(a_seq, taus)
        if self.cfg.arm == 'nocompose':
            z = r @ p
        else:
            z = p @ self._prefix_product(r) @ eye[:, None]   # (b,t,k,k)
        if stats is not None:
            zf = torch.linalg.matrix_norm(z.detach(), dim=(-2, -1))
            a_d = a_seq.detach()
            a_var = float(a_d.var(dim=1).mean())
            a_ms = float(a_d.square().sum((-1, -2)).mean())
            stats['a_var'] = a_var
            stats['a_scale'] = a_ms ** .5
            stats['a_rel'] = a_var / a_ms if a_ms > 0 else 0.0
            stats['z_norm'] = float(zf.mean())
            stats['z_last'] = float(zf[:, -1].mean())
            stats['z_ratio'] = float(zf[:, -1].mean()) / (k ** .5)
            stats['tau_mean'] = float(taus.detach().mean())
            stats['tau_std'] = float(taus.detach().std())
            stats['R_norm_last'] = float(torch.linalg.matrix_norm(
                self._prefix_product(r.detach())[:, -1], dim=(-2, -1)).mean())

        # the action: Z acts on a space of its own, then the result is sent back
        s = self.to_s(h).reshape(b, t, k, q)
        return h + self.out(rho_split(z, s).reshape(b, t, k * q))


class AlgebraModel(nn.Module):
    """Backbone + structural stream. `vocab` and `n_fields` describe the input."""

    def __init__(self, cfg: AlgebraConfig, vocab: int, n_fields: int = 4):
        super().__init__()
        self.cfg = cfg
        self.enc = nn.ModuleList(nn.Embedding(vocab, cfg.width) for _ in range(n_fields))
        self.blocks = nn.ModuleList(LocalBlock(cfg.width, cfg.window) for _ in range(cfg.layers))
        # one generator for the whole model: the law is shared, the interface is
        # per layer. Created before `state` so that every arm draws the same
        # trunk initialisation from the same RNG state.
        self.gen = Generator(cfg.dt, cfg.memory)
        self.state = nn.ModuleDict({str(i): AlgebraState(cfg, self.gen)
                                    for i in cfg.state_layers if cfg.arm != 'off'})
        self.norm = nn.LayerNorm(cfg.width)
        self.head = nn.Linear(cfg.width, vocab)

    def forward(self, events: Tensor, stats: dict | None = None):
        x = sum(emb(events[..., i]) for i, emb in enumerate(self.enc))
        for i, blk in enumerate(self.blocks):
            x = blk(x)                      # LocalBlock carries its own residual
            if str(i) in self.state:
                x = self.state[str(i)](x, stats)
        return self.head(self.norm(x))

    def generators(self):
        return self.gen.values()
